/**
 * @file rgw_ctypes.h
 * @brief 基本 C 类型定义
 */
#ifndef RGW_CTYPES_H
#define RGW_CTYPES_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* 基本类型别名 */
typedef int8_t   rgw_int8_t;
typedef uint8_t  rgw_uint8_t;
typedef int16_t  rgw_int16_t;
typedef uint16_t rgw_uint16_t;
typedef int32_t  rgw_int32_t;
typedef uint32_t rgw_uint32_t;
typedef int64_t  rgw_int64_t;
typedef uint64_t rgw_uint64_t;

#endif /* RGW_CTYPES_H */
